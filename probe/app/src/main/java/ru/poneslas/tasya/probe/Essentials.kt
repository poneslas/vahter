    /** Итог пункта по его проверкам. */
    fun verdict(e: Essential, results: Map<String, ProbeResult>): Status {
        val st = e.probes.map { results[it]?.status ?: Status.NOT_RUN }
        return when {
            st.all { it == Status.NOT_RUN } -> Status.NOT_RUN
            st.any { it == Status.RUNNING } -> Status.RUNNING
            st.any { it == Status.FAIL } -> Status.FAIL
            st.all { it == Status.PASS } -> Status.PASS
            else -> Status.PARTIAL
        }
    }

    /** Слово для человека. */
    fun word(s: Status) = when (s) {
        Status.PASS -> "работает"
        Status.FAIL -> "не работает"
        Status.PARTIAL -> "частично"
        Status.RUNNING -> "идёт проверка"
        else -> "не проверено"
    }
